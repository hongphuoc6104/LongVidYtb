    algorithmic_engine: str
    hook_3s_formula: str
    short_to_long_cliffhanger: str
    long_retention_reset_rule: str
    visual_pacing_directive: str
    next_3_viral_blueprints: tuple[dict[str, str], ...]
    sim_priority_rank: int = 999
    sim_slot_id: str | None = None


