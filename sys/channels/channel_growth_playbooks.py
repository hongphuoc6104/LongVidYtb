# --- 3. HELPER FUNCTIONS ---


def get_channel_playbook(channel_id: str) -> ChannelGrowthPlaybook:
    """Retrieve the growth playbook for a channel, resolving any known aliases.

    Args:
        channel_id: The canonical channel ID or known alias (e.g. 'en_scale_and_bone').

    Returns:
        The corresponding ChannelGrowthPlaybook instance.

    Raises:
        KeyError: If the channel_id is not found in the registry.
    """
    resolved_id = CHANNEL_ALIASES.get(channel_id, channel_id)
    if resolved_id not in CHANNEL_GROWTH_PLAYBOOKS:
        available = len(CANONICAL_CHANNEL_IDS)
        raise KeyError(f"Unknown channel_id '{channel_id}'. Available: {available} physical channels.")
    return CHANNEL_GROWTH_PLAYBOOKS[resolved_id]


def get_sim_verification_priority_queue() -> list[ChannelGrowthPlaybook]:
    """Return the ordered list of 12 channels allocated to the remaining Tier-2 SIM verification slots.

    Allocates across the user's 4 physical SIM cards:
    - SIM 3 (Fresh, 0559745970): 2 SMS + 2 Voice slots (Ranks 1..4)
    - SIM 4 (Fresh, 0559238139): 2 SMS + 2 Voice slots (Ranks 5..8)
    - SIM 1 (Used, 0794999539): 2 Voice slots (Ranks 9..10)
    - SIM 2 (Used, 0398658115): 2 Voice slots (Ranks 11..12)

    Returns:
        List of 12 ChannelGrowthPlaybook instances sorted by priority rank 1 to 12.
    """
    allocated: list[ChannelGrowthPlaybook] = []
    seen_ids: set[str] = set()

    # Collect unique canonical channels with sim_priority_rank in 1..12
    for playbook in CHANNEL_GROWTH_PLAYBOOKS.values():
        if 1 <= playbook.sim_priority_rank <= 12 and playbook.channel_id not in seen_ids:
            seen_ids.add(playbook.channel_id)
            allocated.append(playbook)

    return sorted(allocated, key=lambda p: p.sim_priority_rank)


def list_all_channel_playbooks(include_aliases: bool = False) -> list[ChannelGrowthPlaybook]:
    """Return list of all channel playbooks.

    Args:
        include_aliases: If False, returns only the 38 canonical physical channels.
                         If True, includes aliases as well.
    """
    if include_aliases:
        return list(CHANNEL_GROWTH_PLAYBOOKS.values())
    return [CHANNEL_GROWTH_PLAYBOOKS[cid] for cid in CANONICAL_CHANNEL_IDS]
