from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class SimSlotAllocation:
    """Represents a specific SIM verification slot on a physical phone number."""

    slot_id: str
    phone_number: str
    carrier: str
    verification_method: str  # "sms" or "voice_call"
    slot_index: int  # 1..4 (1-2 SMS, 3-4 Voice Call)
    channel_id: str
    is_historical: bool = False
    notes: str = ""


@dataclass(frozen=True)
class ChannelGrowthPlaybook:
    """Bespoke algorithmic growth playbook for an individual channel."""

    channel_id: str
    display_name: str
    handle: str
    language: str  # "vi" or "en"
    cohort_tier: str  # "vn_breakthrough", "vn_mid_tier", "vn_cold_pivot", "en_velocity_leader", "en_high_conversion", "en_breakout_queue"
